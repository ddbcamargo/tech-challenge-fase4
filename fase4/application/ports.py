"""Contratos entre a aplicação e seus adaptadores externos."""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

from ..domain.anomalies import Anomaly


class PatientStore(Protocol):
    def bootstrap(self) -> int: ...
    def patients(self) -> list[dict]: ...
    def vitals(self, patient_id: str) -> list[dict]: ...
    def prescriptions(self, patient_id: str) -> list[dict]: ...
    def movements(self, patient_id: str) -> list[dict]: ...
    def alerts(self, patient_id: str | None = None) -> list[dict]: ...
    def media_events(self, patient_id: str, modality: str = "audio",
                     limit: int = 20) -> list[dict]: ...
    def review_alert(self, alert_id: int, patient_id: str, status: str) -> bool: ...
    def save_alert(self, alert: Anomaly) -> None: ...
    def save_media_event(self, patient_id: str, modality: str,
                         source_name: str, result: dict) -> int: ...
    def import_physionet(self, path: str | Path, patient_id: str) -> int: ...


class SpeechAnalyzer(Protocol):
    def transcribe(self, path: str | Path) -> str: ...
    def analyze(self, text: str) -> dict: ...


class AudioInspector(Protocol):
    def inspect(self, path: str | Path) -> dict: ...


class PoseAnalyzer(Protocol):
    def analyze(self, path: str | Path) -> list[dict]: ...
    def inspect(self, path: str | Path) -> dict: ...
    def prepare(self) -> dict: ...
    def status(self) -> dict: ...


class AudioSetCatalog(Protocol):
    def preview(self, path: str | Path, limit: int) -> list[dict]: ...
    def speech_examples(self, path: str | Path, limit: int) -> list[dict]: ...


class AudioSetSamples(Protocol):
    def select(self, label: str = "Speech", split: str = "balanced_train",
               limit: int = 24) -> dict: ...
    def status(self) -> dict: ...
    def import_clip(self, clip_id: str, path: str | Path) -> dict: ...
    def training_references(self) -> tuple[list[Path], dict]: ...


class StratifiedAudioSetCatalog(Protocol):
    def select(self, seed: int = 42, train_quotas: dict | None = None,
               eval_quotas: dict | None = None) -> dict: ...
    def status(self) -> dict: ...
    def import_clip(self, clip_id: str, path: str | Path) -> dict: ...
    def references(self, category: str, split: str = "balanced_train") -> tuple[list[Path], dict]: ...


class DatasetProvider(Protocol):
    def prepare(self, root: str | Path) -> dict: ...
    def validate(self, root: str | Path) -> dict: ...



class VoiceAnomalyModel(Protocol):
    def status(self) -> dict: ...
    def train_demo(self) -> dict: ...
    def train_from_directory(self, directory: str | Path) -> dict: ...
    def analyze(self, path: str | Path) -> dict: ...
    def prepare_demo(self, directory: str | Path) -> dict: ...
    def train_from_audioset(self, paths: list[Path], provenance: dict) -> dict: ...
